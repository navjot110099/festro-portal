export function campaignTotals(list: Campaign[] = campaigns) {
  const paid = list.filter((c) => c.platform !== "Organic");
  const spend = paid.reduce((a, c) => a + c.spend, 0);
  const paidRevenue = paid.reduce((a, c) => a + c.revenue, 0);
  return {
    budget: paid.reduce((a, c) => a + c.budget, 0),
    spend,
    leads: list.reduce((a, c) => a + c.leads, 0),
    conversions: list.reduce((a, c) => a + c.conversions, 0),
    revenue: list.reduce((a, c) => a + c.revenue, 0),
    roas: spend ? paidRevenue / spend : 0,
    active: list.filter((c) => c.status === "active" || c.status === "learning").length,
  };
}
